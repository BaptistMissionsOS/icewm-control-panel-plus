    lockCmdEntry->set_hexpand(true);
    r5->pack_start(*l5, Gtk::PACK_SHRINK);
    r5->pack_start(*lockCmdEntry, Gtk::PACK_EXPAND_WIDGET);
    pack_start(*r5, Gtk::PACK_SHRINK);
    auto* r6 = Gtk::manage(new Gtk::Box(Gtk::ORIENTATION_HORIZONTAL, 5));
