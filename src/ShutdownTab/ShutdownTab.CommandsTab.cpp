void ShutdownCommandsTab::setDefaults() {
    shutdownCmdEntry->set_text("/sbin/shutdown -h now");
    rebootCmdEntry->set_text("/sbin/shutdown -r now");
    suspendCmdEntry->set_text("systemctl suspend");
    hibernateCmdEntry->set_text("systemctl hibernate");
    lockCmdEntry->set_text("xscreensaver-command -lock");
    clockCmdEntry->set_text("xclock");
    mailCmdEntry->set_text("thunderbird");
    runCmdEntry->set_text("xterm");
}
