    l6->set_size_request(100, -1);
    clockCmdEntry = Gtk::manage(new Gtk::Entry());
    clockCmdEntry->set_text("xclock");
    clockCmdEntry->set_hexpand(true);
    r6->pack_start(*l6, Gtk::PACK_SHRINK);
