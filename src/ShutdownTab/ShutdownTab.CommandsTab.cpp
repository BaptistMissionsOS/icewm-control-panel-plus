    auto* l4 = Gtk::manage(new Gtk::Label("Hibernate:"));
    l4->set_size_request(100, -1);
    hibernateCmdEntry = Gtk::manage(new Gtk::Entry());
    hibernateCmdEntry->set_text("systemctl hibernate");
    hibernateCmdEntry->set_hexpand(true);
    r4->pack_start(*l4, Gtk::PACK_SHRINK);
    r4->pack_start(*hibernateCmdEntry, Gtk::PACK_EXPAND_WIDGET);
    pack_start(*r4, Gtk::PACK_SHRINK);
    auto* r5 = Gtk::manage(new Gtk::Box(Gtk::ORIENTATION_HORIZONTAL, 5));
